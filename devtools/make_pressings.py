#!/usr/bin/env python3
"""Generate hash-only first-release evidence from the original US 1999 disc, never game bytes.

Pass --disc the raw .bin extracted from the US first pressing. --check verifies the checked-in table against
the actual disc and current manifest. The disc must first prove to be a US Windows disc of the game: most of the
edition's files it holds are exactly the accepted ones. No hash or id of the disc itself is written anywhere.
SAM files and films are excluded even if their old contents are known. Only required Windows manifest destinations
whose original disc contents differ from ALL accepted hashes contribute. Nothing here makes old files accepted.
"""
import argparse
import hashlib
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parent.parent


class Disc:
    def __init__(self, path):
        self.file = open(path, "rb")

    def read(self, offset, size):
        out = bytearray()
        while size:
            sector, inside = divmod(offset, 2048)
            n = min(size, 2048 - inside)
            self.file.seek(sector * 2352 + 16 + inside)
            part = self.file.read(n)
            if len(part) != n:
                raise ValueError("truncated disc")
            out.extend(part)
            offset += n
            size -= n
        return bytes(out)

    def files(self):
        pvd = self.read(16 * 2048, 2048)
        if pvd[:7] != b"\x01CD001\x01":
            raise ValueError("not a mode 1 ISO 9660 disc")
        def directory(rec, parent):
            extent = int.from_bytes(rec[2:6], "little")
            size = int.from_bytes(rec[10:14], "little")
            data = self.read(extent * 2048, size)
            pos = 0
            while pos < len(data):
                n = data[pos]
                if not n:
                    pos = (pos // 2048 + 1) * 2048
                    continue
                row = data[pos:pos+n]
                pos += n
                name = row[33:33+row[32]]
                if name in (b"\0", b"\1"):
                    continue
                path = parent + name.decode("ascii").split(";")[0]
                if row[25] & 2:
                    yield from directory(row, path + "/")
                else:
                    yield path, int.from_bytes(row[2:6], "little") * 2048, int.from_bytes(row[10:14], "little")
        return directory(pvd[156:190], "")


def generate(disc_path, manifest):
    helper = runpy.run_path(str(ROOT / "devtools/make_manifest.py"))
    records, _ = helper["parse_inc"](str(manifest))
    accepted = {dest.lower(): (dest, hs) for dest, hs, _, bits, _, flags in records if bits & 16 and flags & 1}
    disc = Disc(disc_path)
    found, same = {}, 0
    for path, offset, size in disc.files():
        low = path.lower()
        if low.endswith(".sam") or low.startswith("data/movies/"):
            continue
        if low.startswith("usenglish/meshes/american/") or low.startswith("usenglish/filter/american/"):
            low = "data/language/american/" + low.rsplit("/", 1)[-1]
        if low not in accepted:
            continue
        dest, hashes = accepted[low]
        sha = hashlib.sha256(disc.read(offset, size)).hexdigest()
        if (size, sha) in hashes:
            same += 1
        else:
            if dest in found and found[dest] != (size, sha):
                raise ValueError("conflicting contents for " + dest)
            found[dest] = (size, sha)
    if same * 2 <= same + len(found):
        raise ValueError("not a US Windows disc of the game: too few of its files are the accepted ones")
    if len(found) < 3:
        raise ValueError("too few changed core files")
    lines = ["// Generated by devtools/make_pressings.py from the US 1999 first release (the Windows CD 1.0).",
             "// Hashes, sizes and names only of the files it changed; SAM and films excluded.",
             "const PressingFingerprint kPressingFingerprints[] = {"]
    for dest, (size, sha) in sorted(found.items()):
        digest = ",".join("0x" + sha[i:i+2] for i in range(0, 64, 2))
        lines.append('    {"%s", %dull, {{%s}}, Pressing::UsFirstRelease},' % (dest, size, digest))
    return "\n".join(lines + ["};", ""])


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--disc", required=True, type=Path)
    ap.add_argument("--manifest", type=Path, default=ROOT / "assets/manifest_data.inc")
    ap.add_argument("--out", type=Path, default=ROOT / "assets/pressing_data.inc")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = generate(a.disc, a.manifest)
    if a.check:
        if a.out.read_text() != text:
            raise SystemExit("pressing fingerprints differ")
        print("pressing fingerprints verified against original disc")
    else:
        a.out.write_text(text)
        print("wrote " + str(a.out))


if __name__ == "__main__":
    main()
